Epd2in9V2::Epd2in9V2(PanelIo io)
: Ssd16xxPanel(std::move(io), kWidth, kHeight,
    // BUSY polling of Waveshare's epd2in9_V2.py: the C driver's extra 50 ms after BUSY drops only adds latency.
    BusyTiming{ milliseconds{ 0 }, milliseconds{ 10 }, milliseconds{ 0 } }) {
}

std::string Epd2in9V2::name() const {
  return "Waveshare 2.9in V2 (SSD1680)";
}

bool Epd2in9V2::supports(RefreshMode /*mode*/) const noexcept {
  return true;
}

bool Epd2in9V2::resumes_after_sleep() const noexcept {
  return true;
}

void Epd2in9V2::init() {
  _initialized = false;
  _rams_hold_last_frame = false;
  power_on();
  initialize(Waveform::kFull);
  _initialized = true;
}

void Epd2in9V2::display(const Framebuffer& framebuffer, RefreshMode mode) {
  check_size(framebuffer);
  if (!_initialized) {
    throw std::logic_error(name() + ": init() must be called before display()");
  }
  switch (mode) {
    case RefreshMode::kFull:
      display_full(framebuffer, Waveform::kFull);
      return;
    case RefreshMode::kFast:
      display_full(framebuffer, Waveform::kFast);
      return;
    case RefreshMode::kPartial:
      display_partial(framebuffer);
      return;
  }
  throw std::invalid_argument(name() + ": unknown refresh mode");
}

void Epd2in9V2::sleep() {
  command(0x10);  // deep sleep mode 1
  data(0x01);
  delay(milliseconds{ 100 });
  power_off();
  _initialized = false;
  _waveform = Waveform::kNone;
}

void Epd2in9V2::initialize(Waveform waveform) {
  hardware_reset(milliseconds{ 10 }, milliseconds{ 2 }, milliseconds{ 10 });
  delay(milliseconds{ 100 });
  wait_busy(kCommandTimeout);
  command(0x12);  // software reset, keeps the RAM
  wait_busy(kCommandTimeout);

  command(0x01);  // driver output control: 296 gate lines
  data({ 0x27, 0x01, 0x00 });
  command(0x11);  // data entry mode: x and y increment
  data(0x03);
  set_window(0, 0, kWidth - 1, kHeight - 1);
  if (waveform == Waveform::kFast) {
    command(0x3C);  // border waveform
    data(0x05);
  }
  command(0x21);  // display update control
  data({ 0x00, 0x80 });
  set_cursor(0, 0);
  wait_busy(kCommandTimeout);

  load_waveform(waveform == Waveform::kFast ? kWaveformFast : kWaveformFull);
  _waveform = waveform;
}

void Epd2in9V2::load_waveform(const std::uint8_t* table) {
  command(0x32);  // LUT
  data(table, kLutSize);
  wait_busy(kCommandTimeout);
  command(0x3F);  // end option
  data(table[153]);
  command(0x03);  // gate driving voltage
  data(table[154]);
  command(0x04);  // source driving voltage: VSH1, VSH2, VSL
  data({ table[155], table[156], table[157] });
  command(0x2C);  // VCOM
  data(table[158]);
}

void Epd2in9V2::write_both_rams(const Framebuffer& framebuffer) {
  // 0x26 is the "previous" image partial refreshes are computed against.
  set_window(0, 0, kWidth - 1, kHeight - 1);
  set_cursor(0, 0);
  write_ram(0x24, framebuffer);
  set_cursor(0, 0);
  write_ram(0x26, framebuffer);
}

void Epd2in9V2::display_full(const Framebuffer& framebuffer, Waveform waveform) {
  // Whatever the glass shows is unknown until the update completes.
  _last_frame.reset();
  if (_waveform != waveform) {
    initialize(waveform);
  }
  write_both_rams(framebuffer);
  command(0x22);  // display update sequence: clock + analog on, display mode 1, analog + clock off
  data(0xC7);
  command(0x20);
  wait_busy(kRefreshTimeout);
  _last_frame = framebuffer;
  _rams_hold_last_frame = true;
}

void Epd2in9V2::display_partial(const Framebuffer& framebuffer) {
  if (!_last_frame) {
    display_full(framebuffer, Waveform::kFull);
    return;
  }
  if (_waveform != Waveform::kPartial) {
    if (!_rams_hold_last_frame) {
      // Just woken up: the panel still shows _last_frame, give the controller its copy back.
      write_both_rams(*_last_frame);
    }
    // Waveshare's partial setup. It stays valid until the next init() or full refresh, so back to back partial
    // refreshes skip it.
    hardware_reset(milliseconds{ 0 }, milliseconds{ 1 }, milliseconds{ 2 });
    load_waveform(kWaveformPartial);
    command(0x37);  // display option: RAM ping-pong for display mode 2
    data({ 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00 });
    command(0x3C);  // border waveform
    data(0x80);
    _waveform = Waveform::kPartial;
  }
  _last_frame.reset();
  set_window(0, 0, kWidth - 1, kHeight - 1);
  set_cursor(0, 0);
  write_ram(0x24, framebuffer);
  command(0x22);  // display update sequence: clock + analog on, display mode 2, analog + clock off
  data(0xCF);
  command(0x20);
  wait_busy(kRefreshTimeout);
  _last_frame = framebuffer;
  _rams_hold_last_frame = true;
}

